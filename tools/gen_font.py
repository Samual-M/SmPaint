#!/usr/bin/env python3
"""Pre-render the portable UI bitmap font (Liberation Sans, aliased 11px) into C. Output: font_data.c"""
import sys
from PIL import Image, ImageDraw, ImageFont
out = sys.argv[1]
H = 13; ASC = 10
o = ['/* GENERATED by tools/gen_font.py from Liberation Sans (SIL OFL 1.1) - rendered 11px bitmaps */',
     '#include "font.h"']
def gen(name, path):
    f = ImageFont.truetype(path, 11)
    f.set_variation_by_axes if False else None
    rows = []; adv = []
    for c in range(32, 256):
        ch = chr(c)
        adv.append(max(0, int(round(f.getlength(ch)))) if c != 127 else 0)
        im = Image.new('1', (16, H), 0); d = ImageDraw.Draw(im); d.fontmode = '1'
        d.text((0, ASC), ch, font=f, fill=1, anchor='ls')
        for y in range(H):
            v = 0
            for x in range(16):
                if im.getpixel((x, y)): v |= 1 << (15 - x)
            rows.append(v)
    o.append(f'const unsigned char font_{name}_adv[224] = {{' + ','.join(map(str, adv)) + '};')
    o.append(f'const unsigned short font_{name}_bits[224*{H}] = {{')
    for i in range(0, len(rows), 13): o.append('  ' + ','.join(f'0x{v:04x}' for v in rows[i:i+13]) + ',')
    o.append('};')
gen('reg', '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf')
gen('bold', '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf')
open(out, 'w').write('\n'.join(o) + '\n')
